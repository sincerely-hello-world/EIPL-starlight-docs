/**
 * Preserve manual navigation and append unconfigured top-level document directories.
 * Nested slugs and autogenerated directories also reserve their top-level directory.
 * [Comment Translate] | Bing
	* 保留手动导航并附加未配置的顶层文档目录。
	* 嵌套的路径段和自动生成的目录也保留它们的顶层目录。
 * @param {Sidebar} entries
 * @param {string | URL} docsDirectory
 * @returns {Sidebar}
 */
export function createSidebar(entries, docsDirectory) {
	const configuredDirectories = new Set();

	/** @param {Sidebar} items */
	function collectDirectories(items) {
		for (const item of items) {
			const path = typeof item === 'string'
				? item
				: 'autogenerate' in item
					? item.autogenerate.directory
					: 'slug' in item ? item.slug : '';
			const directory = path.split('/').filter(Boolean)[0];
			if (directory) configuredDirectories.add(directory);
			if (typeof item === 'object' && 'items' in item) collectDirectories(item.items);
		}
	}

	collectDirectories(entries);
	const additionalGroups = readdirSync(docsDirectory, { withFileTypes: true })
		.filter((entry) => entry.isDirectory() && !entry.name.startsWith('.') && !configuredDirectories.has(entry.name))
		.map((entry) => entry.name)
		.sort((a, b) => a.localeCompare(b, 'zh-CN'))
		.map((directory) => ({
			label: directory,
			items: [{ autogenerate: { directory } }],
		}));

	return [...entries, ...additionalGroups];
}

export default createSidebar(manualSidebar, new URL('../src/content/docs/', import.meta.url));
